/** Install one corpus + title fold. `live` maps a session id to its live agent. */
function install(spec) {
  M.reset()
  const live = spec.live === undefined ? {} : spec.live
  M.svcTable.sessionQuery = {
    listSessions: async function () { return spec.corpus },
    /* The real fold reports per session: a log-less session has no title, and
     * that failure must not take the rest of the listing with it. */
    readTitleSnapshots: async function (ids) {
      return ids.map(function (id) {
        const title = spec.titles[id]
        if (title === undefined) return { sessionId: id, status: 'rejected', reason: 'no log on disk' }
        return { sessionId: id, status: 'fulfilled', value: { title: { title: title } } }
      })
    },
  }
  M.svcTable.agents = { get: function (id) { return live[id] } }
}

