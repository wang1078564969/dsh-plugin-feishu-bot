/** Slice host.js between two literal markers; a missing marker is fatal. */
function slice(startMarker, endMarker) {
  const from = src.indexOf(startMarker)
  if (from === -1) throw new Error('host.js: missing start marker: ' + JSON.stringify(startMarker))
  const to = src.indexOf(endMarker, from)
  if (to === -1) {
    throw new Error('host.js: missing end marker after ' + JSON.stringify(startMarker) + ': ' + JSON.stringify(endMarker))
  }
  return src.slice(from, to + endMarker.length)
}

/** Slices are interpolated into a template literal, so their backticks escape. */
function code(startMarker, endMarker) {
  return slice(startMarker, endMarker).replace(/`/g, '\\`')
}

