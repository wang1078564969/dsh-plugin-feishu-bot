/*
 * Which DSH session is a Feishu chat talking to — and what happens when that
 * changes while the chat's own turn is still running.
 *
 * Two rules are pinned here.
 *
 * 1. A chat can be repointed from inside its own turn: the `reset` tool called
 *    on the chat that is running it, `/new`, `/s`. Disposing that agent from
 *    inside its own turn kills the loop executing the tool call, so the swap is
 *    PARKED in deferredSwaps and retried once the turn's capture is gone. A
 *    turn already past its own ceiling can never settle (a step waiting on a
 *    tool result that will never arrive), so the escape hatch detaches the
 *    session WITHOUT awaiting dispose().
 *
 * 2. `agents.resume` must be handed `agentOptions`. The deployment persona
 *    references {{model}}, which dsh-agent-loop resolves from `agent.options`;
 *    a resume that omits it dies at step/start with
 *    `prompt variable "{{model}}" has no value`.
 *
 * The code under test is sliced out of host.js at run time — edit the plugin
 * and this suite changes with it. Nothing here is a copy of the plugin.
 *
 * Run from anywhere: node tests/test-resume.cjs  (or an absolute path to it)
 */
const fs = require('fs')
const path = require('path')

const src = fs.readFileSync(path.join(__dirname, '..', 'lib', 'bot.js'), 'utf8')

/**
 * The verbatim region of host.js between two markers, both inclusive.
 * With no end marker, up to the end of that line. A missing marker is a hard
 * error naming the marker — never a silent skip.
 */
function slice(startMarker, endMarker) {
  const a = src.indexOf(startMarker)
  if (a === -1) throw new Error('missing start marker in host.js: ' + JSON.stringify(startMarker))
  if (endMarker === undefined) {
    const end = src.indexOf('\n', a)
    return src.slice(a, end === -1 ? src.length : end)
  }
  const b = src.indexOf(endMarker, a)
  if (b === -1) {
    throw new Error('missing end marker in host.js: ' + JSON.stringify(endMarker) + ' after ' + JSON.stringify(startMarker))
  }
  return src.slice(a, b + endMarker.length)
}

const S = {
  maxRemembered: slice('const MAX_REMEMBERED_SESSIONS = '),
  describeError: slice('    function describeError(error) {', "      return error.name === undefined ? message : error.name + ': ' + message\n    }"),
  sessionIdFor: slice('    function sessionIdFor(chatId, generation) {', "      return 'feishu-' + safe + (generation > 0 ? '-g' + generation : '')\n    }"),
  rememberedSessions: slice('    function rememberedSessions(entry) {', '      return entry.sessions\n    }'),
  rememberSession: slice('    function rememberSession(entry, id) {', '      if (entry.sessions.length > MAX_REMEMBERED_SESSIONS) entry.sessions.length = MAX_REMEMBERED_SESSIONS\n    }'),
  effectiveTimeout: slice('    function effectiveTimeout() {', "      return typeof config.timeoutMs === 'number' && config.timeoutMs > 0 ? config.timeoutMs : DEFAULTS.timeoutMs\n    }"),
  currentAgentOptions: slice('    function currentAgentOptions() {', '      if (selection.reasoningEffort !== undefined) options.reasoningEffort = selection.reasoningEffort\n      return options\n    }'),
  withSessionSwap: slice('    async function withSessionSwap(chatId, entry, apply) {', '      return apply()\n    }'),
  restartChatSession: slice('    async function restartChatSession(chatId, entry) {', '        entry.sessionId = sessionIdFor(chatId, entry.generation)\n        return entry.sessionId\n      })\n    }'),
  switchChatSession: slice('    async function switchChatSession(chatId, entry, targetId) {', '        entry.sessionId = targetId\n        return entry.sessionId\n      })\n    }'),
  drainDeferredSwap: slice('    async function drainDeferredSwap(chatId, entry) {', "      log('deferred swap applied chat=' + chatId + ' session=' + entry.sessionId)\n    }"),
  acquireAgent: slice('    async function acquireAgent(entry, displayName) {', '      return createAgent(entry, displayName)\n    }'),
}

/* The generated harness lives beside this file, so the suite is relocatable. */
